# 計算 — чистая математика core_magic: без amazake и без Java (проверяется обычным python3, tests_core_magic.py).
#
#   * кодирование параметра шейдера в красный канал цвета custom_model_data (заряд круга, длина луча);
#   * вектор взгляда из yaw/pitch (как Location.getDirection в Bukkit);
#   * путь луча: отрезок [0, R] режется на куски, у каждого куска — AABB и набор столбцов чанков (проверка владения);
#   * попадание: отрезок против AABB (метод плит), отбор целей вдоль отрезка без самого заклинателя;
#   * время: остаток перезарядки, полоска заряда;
#   * барьер (結界): соты шестигранников, порядок сборки, фазы мерцания, кодирование R = g + 25·L, реестр
#     барьеров (結界記録) и пересечение луча с барьером (遮断);
#   * «Огненный шар» (流星): кодирование R = g + 125·B кометы, повороты дисплеев (кватернионы), выбор цели и высоты
#     огненного круга, разброс комет, тики запуска, взрывная волна (точка × AABB), счёт попаданий, отталкивание.

import math
from collections import namedtuple as _nt

#: Метка шейдера (ключ A): G и B цвета — постоянные, R — параметр. НЕ из конфига (их знает шейдер).
印G = 233
印B = 253
R上限 = 250
#: Длина луча в шейдере: L = R / 8 блоков.
一塊のR = 8.0


def 挟む(v, lo, hi):
    return lo if v < lo else hi if v > hi else v


# ------------------------------------------------------------------------------------------- параметр шейдера

def 充填R(charge):
    """Заряд 0..1 → R = round(charge*250) (250 — круг готов)."""
    c = 挟む(float(charge), 0.0, 1.0)
    return int(math.floor(c * R上限 + 0.5))


def 光線R(長さ):
    """Видимая длина луча Lv (блоки) → R = clamp(round(Lv*8), 1, 250)."""
    return int(挟む(int(math.floor(float(長さ) * 一塊のR + 0.5)), 1, R上限))


def 見た目の長さ(届く, 前):
    """Видимая длина луча: от круга (вынесен на 前 вперёд) до точки остановки 届く, но не короче 0.5."""
    return max(0.5, float(届く) - float(前))


def 充填率(ticks, 必要):
    """Доля заряда за ticks тиков удержания (必要 — тиков до полного)."""
    if 必要 <= 0:
        return 1.0
    return 挟む(float(ticks) / float(必要), 0.0, 1.0)


# ------------------------------------------------------------------------------------------- направление

def 視線(yaw, pitch):
    """Единичный вектор взгляда (как Location.getDirection): yaw 0 → +Z, 90 → −X; pitch > 0 — вниз."""
    ry = math.radians(yaw)
    rp = math.radians(pitch)
    xz = math.cos(rp)
    return (-xz * math.sin(ry), -math.sin(rp), xz * math.cos(ry))


def 角度差(a, b):
    """Наименьшая разница углов в градусах (с переходом через 360)."""
    d = (float(a) - float(b)) % 360.0
    return 360.0 - d if d > 180.0 else d


# ------------------------------------------------------------------------------------------- путь луча

def 区切る(長さ, 片長):
    """[0, 長さ] → куски [(a, b)] длиной 片長 (последний короче). 長さ ≤ 0 → []."""
    長さ = float(長さ)
    片長 = max(0.25, float(片長))
    out = []
    a = 0.0
    while a < 長さ - 1e-9:
        b = min(長さ, a + 片長)
        out.append((a, b))
        a = b
    return out


def 点(始, 向き, t):
    return (始[0] + 向き[0] * t, 始[1] + 向き[1] * t, 始[2] + 向き[2] * t)


def 区間の箱(始, 向き, a, b, 余白):
    """AABB куска луча [a, b], расширенный на 余白 во все стороны: (minx, miny, minz, maxx, maxy, maxz)."""
    p = 点(始, 向き, a)
    q = 点(始, 向き, b)
    return (min(p[0], q[0]) - 余白, min(p[1], q[1]) - 余白, min(p[2], q[2]) - 余白,
            max(p[0], q[0]) + 余白, max(p[1], q[1]) + 余白, max(p[2], q[2]) + 余白)


def 箱の列(箱):
    """Столбцы чанков (cx, cz), которых касается AABB (по X и Z)."""
    x0 = int(math.floor(箱[0])) >> 4
    x1 = int(math.floor(箱[3])) >> 4
    z0 = int(math.floor(箱[2])) >> 4
    z1 = int(math.floor(箱[5])) >> 4
    return {(cx, cz) for cx in range(x0, x1 + 1) for cz in range(z0, z1 + 1)}


def 使える長さ(始, 向き, 長さ, 片長, 余白, 持つか):
    """Длина луча, весь путь которой в нашем регионе: идём по кускам, у каждого куска все столбцы его AABB (с
    余白) должны пройти 持つか(cx, cz). Первый непрошедший кусок обрывает луч (как стена). Результат проверок
    столбцов кэшируется (соседние куски делят столбцы)."""
    済 = {}
    使える = 0.0
    for a, b in 区切る(長さ, 片長):
        for col in 箱の列(区間の箱(始, 向き, a, b, 余白)):
            ok = 済.get(col)
            if ok is None:
                ok = bool(持つか(col[0], col[1]))
                済[col] = ok
            if not ok:
                return 使える
        使える = b
    return 使える


def 線分と箱(始, 向き, 長さ, 箱):
    """Метод плит: расстояние t ∈ [0, 長さ], на котором луч входит в AABB, или None. Начало внутри — 0."""
    t0 = 0.0
    t1 = float(長さ)
    for i in range(3):
        o = 始[i]
        d = 向き[i]
        lo = 箱[i]
        hi = 箱[i + 3]
        if abs(d) < 1e-12:
            if o < lo or o > hi:
                return None
            continue
        inv = 1.0 / d
        ta = (lo - o) * inv
        tb = (hi - o) * inv
        if ta > tb:
            ta, tb = tb, ta
        if ta > t0:
            t0 = ta
        if tb < t1:
            t1 = tb
        if t0 > t1:
            return None
    return t0


def 広げる(箱, r):
    return (箱[0] - r, 箱[1] - r, 箱[2] - r, 箱[3] + r, 箱[4] + r, 箱[5] + r)


def 当たり(始, 向き, 長さ, 候補, 自分, 半径):
    """Цели луча: 候補 — [(id, AABB)], 自分 — id заклинателя (никогда не попадает). Бокс каждой цели расширен на
    半径. Возвращает [(t, id)] по возрастанию расстояния, каждый id — один раз."""
    out = {}
    for id, 箱 in 候補:
        if id == 自分 or id in out:
            continue
        t = 線分と箱(始, 向き, 長さ, 広げる(箱, 半径))
        if t is not None:
            out[id] = t
    return sorted(((t, id) for id, t in out.items()), key=lambda x: x[0])


def 道の点(始, 向き, から, まで, 毎):
    """Точки вдоль луча от から до まで через каждые 毎 блоков (для частиц следа)."""
    if 毎 <= 0 or まで <= から:
        return []
    out = []
    t = float(から)
    while t <= まで + 1e-9:
        out.append(点(始, 向き, t))
        t += 毎
    return out


# ------------------------------------------------------------------------------------------- время

def 冷却残り(今ms, 終ms):
    """Сколько секунд ещё перезарядка (0 — готов)."""
    return max(0.0, (float(終ms) - float(今ms)) / 1000.0)


def 秒の文字(秒):
    """Секунды для сообщения: «2.4», без хвоста «.0» («3»)."""
    s = "%.1f" % (math.ceil(float(秒) * 10.0 - 1e-9) / 10.0)
    return s[:-2] if s.endswith(".0") else s


def 充填棒(charge, 長さ, 色="#7fd8ff"):
    """Полоска заряда в MiniMessage: заполненная часть цвета 色 (по умолчанию голубая), остальное — тёмно-серая."""
    n = max(1, int(長さ))
    k = int(math.floor(挟む(float(charge), 0.0, 1.0) * n + 1e-9))
    s = ""
    if k > 0:
        s += "<" + 色 + ">" + "|" * k + "</" + 色 + ">"
    if k < n:
        s += "<dark_gray>" + "|" * (n - k) + "</dark_gray>"
    return s


# ------------------------------------------------------------------------------------------- барьер (結界)
# Барьер — вертикальная стена из шестигранников (pointy-top, вершиной вверх) перед заклинателем. Локальные
# координаты барьера: u — вправо от заклинателя, v — вверх, метры, от центра (якоря). Соты: столбцы C, ряды R
# (ряд 0 — нижний), чётные ряды сдвинуты на −w/4, нечётные — на +w/4 (w = √3·r — ширина ячейки по граням).

#: Радиус описанной окружности шестигранника в спрайте hex_cell.png (пиксели из 128) — общая константа со
#: спрайтом и шейдером (nexo-items/tools/moonstaff_fx.py).
HEX_R_PX = 60
#: Уровни состояния ячейки (L в R = g + 25·L): 0..7 — прозрачность L/8, 8 — обычная, 9 — вспышка.
結界L上限 = 9
輝き上限 = 24

#: Запись реестра барьеров: только чистые данные (без объектов Java) — читается из любого потока.
結界記録 = _nt("結界記録", "id 世界 中心 右 法線 r 細胞 半幅 半高 終ms 主")


def 蜂巣(列, 行, r):
    """Центры ячеек [(u, v)] построчно, нижний ряд первым: k = j*列 + i."""
    列 = max(1, int(列))
    行 = max(1, int(行))
    r = float(r)
    w = math.sqrt(3.0) * r
    h = 1.5 * r
    out = []
    for j in range(行):
        s = -w / 4.0 if j % 2 == 0 else w / 4.0
        for i in range(列):
            out.append(((i - (列 - 1) / 2.0) * w + s, (j - (行 - 1) / 2.0) * h))
    return out


def 組順(cells):
    """Порядок сборки: от центра наружу (по расстоянию, затем по углу от «вверх» по часовой)."""
    def 鍵(k):
        u, v = cells[k]
        return (round(u * u + v * v, 6), round(math.atan2(u, v) % (2.0 * math.pi), 6))
    return sorted(range(len(cells)), key=鍵)


def 輝き番号(cells):
    """Фаза мерцания g (0..24) каждой ячейки по диагонали d = u − v/2: верхняя левая — 0, нижняя правая — 24."""
    if not cells:
        return []
    ds = [u - 0.5 * v for u, v in cells]
    lo = min(ds)
    hi = max(ds)
    if hi - lo <= 1e-12:
        return [0 for _ in ds]
    return [int(math.floor(輝き上限 * (d - lo) / (hi - lo) + 0.5)) for d in ds]


def 結界R(g, L):
    """R = g + 25·L (g 0..24, L 0..9) → 0..249."""
    return int(挟む(int(g), 0, 輝き上限)) + 25 * int(挟む(int(L), 0, 結界L上限))


def 結界R解く(R):
    """Обратно, как шейдер: (L, g)."""
    R = int(R)
    return R // 25, R % 25


def 出現tick(m, N, 充填, 飛):
    """Тик появления ячейки на месте m порядка сборки (последняя долетает ровно к 充填)."""
    if N <= 1:
        return 0
    return int(math.floor(m * (int(充填) - int(飛)) / float(N - 1)))


def 六角内(x, y, r):
    """Точка (x, y) внутри шестигранника (вершиной вверх) с радиусом r и центром в 0 (с краем)."""
    ax = abs(x)
    return ax <= (math.sqrt(3.0) / 2.0) * r + 1e-9 and abs(y) + ax / math.sqrt(3.0) <= r + 1e-9


def 表示倍率(r, 隙間):
    """Масштаб дисплея ячейки: модель — квадрат 1×1 блок, шестигранник в нём радиусом HEX_R_PX/128."""
    return float(r) * (1.0 - float(隙間)) * 128.0 / HEX_R_PX


def 結界の軸(yaw):
    """(右, 法線) барьера для yaw (градусы): 法線 — горизонталь взгляда, 右 — правая рука заклинателя."""
    th = math.radians(float(yaw))
    return (-math.cos(th), 0.0, -math.sin(th)), (-math.sin(th), 0.0, math.cos(th))


def 結界の中心(eye, yaw, 前, 上):
    """Якорь: глаза + 法線·前 (по горизонтали) + (0, 上, 0)."""
    _, n = 結界の軸(yaw)
    return (eye[0] + n[0] * 前, eye[1] + 上, eye[2] + n[2] * 前)


def 結界を作る(id, 世界, eye, yaw, 設定, 今ms, 主):
    """Запись реестра для барьера. 設定 — settei.結界 (前 上 半径 列 行 秒)."""
    r = float(設定.半径)
    細胞 = tuple(蜂巣(設定.列, 設定.行, r))
    右, 法線 = 結界の軸(yaw)
    w = math.sqrt(3.0) * r
    半幅 = max(abs(u) for u, _ in 細胞) + w / 2.0
    半高 = max(abs(v) for _, v in 細胞) + r
    return 結界記録(int(id), str(世界), 結界の中心(eye, yaw, 設定.前, 設定.上), 右, 法線, r, 細胞, 半幅, 半高,
                  int(今ms + 設定.秒 * 1000.0), str(主))


def _内積(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def 線分と結界(E, d, D, rec):
    """Отрезок E + d·t, t ∈ [0, D] против барьера rec: (t, k) — где и какая ячейка, или None (мимо, в зазубрину
    края, параллельно плоскости)."""
    n = rec.法線
    den = _内積(n, d)
    if abs(den) < 1e-9:
        return None
    c = rec.中心
    t = (n[0] * (c[0] - E[0]) + n[1] * (c[1] - E[1]) + n[2] * (c[2] - E[2])) / den
    if t < 0.0 or t > D:
        return None
    q = (E[0] + d[0] * t - c[0], E[1] + d[1] * t - c[1], E[2] + d[2] * t - c[2])
    u = _内積(q, rec.右)
    v = q[1]
    if abs(u) > rec.半幅 + 1e-9 or abs(v) > rec.半高 + 1e-9:
        return None
    for k, (cu, cv) in enumerate(rec.細胞):
        if 六角内(u - cu, v - cv, rec.r):
            return t, k
    return None


def 遮断(E, d, D, recs, 世界, 今ms):
    """Ближайший барьер на пути луча: (t, id, k) или None. Чужой мир и истёкшие записи пропускаются."""
    best = None
    for rec in recs:
        if rec.世界 != 世界 or rec.終ms <= 今ms:
            continue
        h = 線分と結界(E, d, D, rec)
        if h is not None and (best is None or h[0] < best[0]):
            best = (h[0], rec.id, h[1])
    return best


def 手前か(rec, p, E):
    """Точка p по ту же сторону плоскости барьера, что и глаза E (на плоскости — тоже «перед»)."""
    c = rec.中心
    n = rec.法線
    sp = n[0] * (p[0] - c[0]) + n[1] * (p[1] - c[1]) + n[2] * (p[2] - c[2])
    se = n[0] * (E[0] - c[0]) + n[1] * (E[1] - c[1]) + n[2] * (E[2] - c[2])
    return sp * se >= 0.0


# ------------------------------------------------------------------------------------------- «Огненный шар» (流星)
# Огненный круг (модель azerus:moon_staff_fire_circle, спрайты K11..14) висит горизонтально высоко над целью; после
# заряда из него падают кометы (модель azerus:moon_staff_comet, спрайты K15..19). Кватернионы — (x, y, z, w), как
# Quaternionf в JOML; поворот вектора — q·v·q⁻¹.

#: Комета: R = g + 125·B — g 0..124 фаза мерцания, B 0 — падает, 1 — вспышка удара (шейдер K15..19).
流星B基 = 125
流星g上限 = 124


def 流星R(g, B):
    """R = g + 125·B (g 0..124, B 0..1) → 0..249."""
    return int(挟む(int(g), 0, 流星g上限)) + 流星B基 * int(挟む(int(B), 0, 1))


def 流星R解く(R):
    """Обратно, как шейдер: (g, B)."""
    code = int(math.floor(int(R) / float(R上限) * R上限 + 0.5))
    B = code // 流星B基
    return code - 流星B基 * B, B


def 四元数積(a, b):
    """a·b (сначала b, потом a — как Quaternionf.mul)."""
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return (aw * bx + ax * bw + ay * bz - az * by,
            aw * by - ax * bz + ay * bw + az * bx,
            aw * bz + ax * by - ay * bx + az * bw,
            aw * bw - ax * bx - ay * by - az * bz)


def 四元数で回す(q, v):
    """Повернуть вектор v кватернионом q (единичным)."""
    x, y, z, w = q
    r = 四元数積(四元数積(q, (v[0], v[1], v[2], 0.0)), (-x, -y, -z, w))
    return (r[0], r[1], r[2])


#: Y на π: так ItemDisplay сам поворачивает модель (см. kyoutsuu.変形 反転).
Y反転 = (0.0, 1.0, 0.0, 0.0)
#: Огненный круг: L = rotationX(π/2)·rotateY(π) → вместе с поворотом самого дисплея — Rx(π/2): +Z модели → −Y мира
#: (круг лежит горизонтально, «лицом» вниз), +Y модели → +Z мира.
炎陣回転 = (0.0, math.sqrt(0.5), math.sqrt(0.5), 0.0)


def 正規化(v):
    n = math.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2])
    if n < 1e-12:
        return None
    return (v[0] / n, v[1] / n, v[2] / n)


def 流星回転(u):
    """Комета: хвост модели (+Z) → u (единичный, от точки удара к точке старта) с учётом поворота дисплея на 180°:
    q = rotationTo(+Z → u)·Ry(π) (JOML: Quaternionf().rotationTo(0,0,1, ux,uy,uz).rotateY(π)). u ≈ −Z — ось Y, π."""
    u = 正規化(u) or (0.0, 1.0, 0.0)
    dot = u[2]
    if dot < -1.0 + 1e-6:
        rt = (0.0, 1.0, 0.0, 0.0)
    else:
        # ось = (0,0,1) × u, w = 1 + cos
        q = (-u[1], u[0], 0.0, 1.0 + dot)
        n = math.sqrt(q[0] * q[0] + q[1] * q[1] + q[3] * q[3])
        rt = (q[0] / n, q[1] / n, 0.0, q[3] / n)
    return 四元数積(rt, Y反転)


def 狙い(E, d, Lu, tB, 上面か, tE, 足, 法線=None):
    """Точка цели «Огненного шара»: (P_raw, 落とすか). tB — расстояние до блока (None — нет), 上面か — попали в верх
    блока, 法線 — нормаль грани (x, y, z); tE — расстояние до существа (None — нет), 足 — его ноги.
    Существо раньше блока → его ноги; верх блока → точка удара; другая грань → на 0.3 от грани и вниз до земли;
    ничего → конец доступного пути и вниз."""
    if tE is not None and (tB is None or tE <= tB):
        return (float(足[0]), float(足[1]), float(足[2])), False
    if tB is not None:
        H = 点(E, d, tB)
        if 上面か:
            return H, False
        n = 法線 or (0.0, 0.0, 0.0)
        return (H[0] + n[0] * 0.3, H[1] + n[1] * 0.3, H[2] + n[2] * 0.3), True
    return 点(E, d, Lu), True


def 炎陣の高さ(Py, 高さ, 天井y, 最高y, 隙間, 最低):
    """Высота центра огненного круга над точкой цели Py: Py + 高さ, но под потолком (天井y − 隙間) и ниже предела
    мира (最高y − 1.5). Места меньше 最低 — None («здесь круг не раскроется»)."""
    Cy = float(Py) + float(高さ)
    if 天井y is not None:
        Cy = min(Cy, float(天井y) - float(隙間))
    Cy = min(Cy, float(最高y) - 1.5)
    if Cy - float(Py) < float(最低):
        return None
    return Cy


def 炎陣の大きさ(直径, 始倍, charge):
    """Масштаб огненного круга при заряде charge (модель кольца — 1 блок)."""
    return float(直径) * (float(始倍) + (1.0 - float(始倍)) * 挟む(float(charge), 0.0, 1.0))


def 円内の点(半径, rng):
    """Случайная точка (dx, dz) равномерно в круге 半径."""
    r = float(半径) * math.sqrt(rng.random())
    th = 2.0 * math.pi * rng.random()
    return (r * math.cos(th), r * math.sin(th))


def 落下点(n, 半径, 中心から, rng):
    """Точки падения n комет [(dx, dz)] вокруг цели: равномерно в круге 半径; 中心から — первая точно в цель."""
    out = []
    for i in range(max(0, int(n))):
        if i == 0 and 中心から:
            out.append((0.0, 0.0))
        else:
            out.append(円内の点(半径, rng))
    return out


def 出発係数(広がり, 直径, 散半径):
    """k: насколько точки старта комет в круге разнесены по сравнению с точками падения (≤ 1 — кометы расходятся)."""
    return min(1.0, float(広がり) * float(直径) / 2.0 / max(float(散半径), 1e-6))


def 出発点(C, P, 点, k, 揺れ, rng):
    """Точка старта кометы S: внутри круга C, над точкой падения, сжатая к центру (k), ± 揺れ по X и Z, чуть ниже
    плоскости круга."""
    dx, dz = 点
    jx = rng.uniform(-揺れ, 揺れ) if 揺れ > 0 else 0.0
    jz = rng.uniform(-揺れ, 揺れ) if 揺れ > 0 else 0.0
    return (C[0] + k * dx + jx, C[1] - 0.2, C[2] + k * dz + jz)


def 発射tick(n, 間隔):
    """Тики запуска комет после отпускания: s_i = ⌊i·間隔/(n−1)⌋ (n = 1 → [0])."""
    n = max(0, int(n))
    if n <= 1:
        return [0] * n
    return [int(math.floor(i * int(間隔) / float(n - 1))) for i in range(n)]


def 着弾tick(s, 落下):
    """Тик удара кометы, запущенной на s: появление на 1 + s, падение с 2 + s, удар на 2 + s + 落下."""
    return 2 + int(s) + int(落下)


def 最後の着弾(n, 間隔, 落下):
    s = 発射tick(n, 間隔)
    return 着弾tick(max(s) if s else 0, 落下)


def 線形(a, b, t):
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t)


def 箱までの距離(p, 箱):
    """Расстояние от точки до AABB (внутри — 0)."""
    dx = max(箱[0] - p[0], 0.0, p[0] - 箱[3])
    dy = max(箱[1] - p[1], 0.0, p[1] - 箱[4])
    dz = max(箱[2] - p[2], 0.0, p[2] - 箱[5])
    return math.sqrt(dx * dx + dy * dy + dz * dz)


def 爆風(I, r, 候補, 自分):
    """Цели взрыва в точке I: [id] у которых хитбокс ближе r, по возрастанию расстояния, без 自分 и без повторов."""
    out = {}
    for id, 箱 in 候補:
        if id == 自分 or id in out:
            continue
        d = 箱までの距離(I, 箱)
        if d <= r:
            out[id] = d
    return [id for id, _ in sorted(out.items(), key=lambda x: x[1])]


def 数える(回数, id, 上限):
    """Ещё можно задеть id (меньше 上限 попаданий за заклинание)? Да — счёт +1."""
    n = 回数.get(id, 0)
    if n >= int(上限):
        return False
    回数[id] = n + 1
    return True


def 押し出し(I, 中心, 強さ, 上):
    """Отталкивание от точки удара: горизонталь (от I к центру цели) нормированная × 強さ, плюс 上 вверх; цель почти
    в точке удара — только вверх."""
    dx = 中心[0] - I[0]
    dz = 中心[2] - I[2]
    h = math.sqrt(dx * dx + dz * dz)
    if h < 0.1:
        return (0.0, float(上), 0.0)
    return (dx / h * 強さ, float(上), dz / h * 強さ)
