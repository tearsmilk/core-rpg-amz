# 計算 — чистая математика core_magic: без amazake и без Java (проверяется обычным python3, tests_core_magic.py).
#
#   * кодирование параметра шейдера в красный канал цвета custom_model_data (заряд круга, длина луча);
#   * вектор взгляда из yaw/pitch (как Location.getDirection в Bukkit);
#   * путь луча: отрезок [0, R] режется на куски, у каждого куска — AABB и набор столбцов чанков (проверка владения);
#   * попадание: отрезок против AABB (метод плит), отбор целей вдоль отрезка без самого заклинателя;
#   * время: остаток перезарядки, полоска заряда.

import math

#: Метка шейдера (ключ A): G и B цвета — постоянные, R — параметр. НЕ из конфига (их знает шейдер).
印G = 233
印B = 253
R上限 = 250
#: Длина луча в шейдере: L = R / 8 блоков.
一塊のR = 8.0


def 挟む(v, lo, hi):
    return lo if v < lo else hi if v > hi else v


# ------------------------------------------------------------------------------------------- параметр шейдера

def 充填R(charge):
    """Заряд 0..1 → R = round(charge*250) (250 — круг готов)."""
    c = 挟む(float(charge), 0.0, 1.0)
    return int(math.floor(c * R上限 + 0.5))


def 光線R(長さ):
    """Видимая длина луча Lv (блоки) → R = clamp(round(Lv*8), 1, 250)."""
    return int(挟む(int(math.floor(float(長さ) * 一塊のR + 0.5)), 1, R上限))


def 見た目の長さ(届く, 前):
    """Видимая длина луча: от круга (вынесен на 前 вперёд) до точки остановки 届く, но не короче 0.5."""
    return max(0.5, float(届く) - float(前))


def 充填率(ticks, 必要):
    """Доля заряда за ticks тиков удержания (必要 — тиков до полного)."""
    if 必要 <= 0:
        return 1.0
    return 挟む(float(ticks) / float(必要), 0.0, 1.0)


# ------------------------------------------------------------------------------------------- направление

def 視線(yaw, pitch):
    """Единичный вектор взгляда (как Location.getDirection): yaw 0 → +Z, 90 → −X; pitch > 0 — вниз."""
    ry = math.radians(yaw)
    rp = math.radians(pitch)
    xz = math.cos(rp)
    return (-xz * math.sin(ry), -math.sin(rp), xz * math.cos(ry))


def 角度差(a, b):
    """Наименьшая разница углов в градусах (с переходом через 360)."""
    d = (float(a) - float(b)) % 360.0
    return 360.0 - d if d > 180.0 else d


# ------------------------------------------------------------------------------------------- путь луча

def 区切る(長さ, 片長):
    """[0, 長さ] → куски [(a, b)] длиной 片長 (последний короче). 長さ ≤ 0 → []."""
    長さ = float(長さ)
    片長 = max(0.25, float(片長))
    out = []
    a = 0.0
    while a < 長さ - 1e-9:
        b = min(長さ, a + 片長)
        out.append((a, b))
        a = b
    return out


def 点(始, 向き, t):
    return (始[0] + 向き[0] * t, 始[1] + 向き[1] * t, 始[2] + 向き[2] * t)


def 区間の箱(始, 向き, a, b, 余白):
    """AABB куска луча [a, b], расширенный на 余白 во все стороны: (minx, miny, minz, maxx, maxy, maxz)."""
    p = 点(始, 向き, a)
    q = 点(始, 向き, b)
    return (min(p[0], q[0]) - 余白, min(p[1], q[1]) - 余白, min(p[2], q[2]) - 余白,
            max(p[0], q[0]) + 余白, max(p[1], q[1]) + 余白, max(p[2], q[2]) + 余白)


def 箱の列(箱):
    """Столбцы чанков (cx, cz), которых касается AABB (по X и Z)."""
    x0 = int(math.floor(箱[0])) >> 4
    x1 = int(math.floor(箱[3])) >> 4
    z0 = int(math.floor(箱[2])) >> 4
    z1 = int(math.floor(箱[5])) >> 4
    return {(cx, cz) for cx in range(x0, x1 + 1) for cz in range(z0, z1 + 1)}


def 使える長さ(始, 向き, 長さ, 片長, 余白, 持つか):
    """Длина луча, весь путь которой в нашем регионе: идём по кускам, у каждого куска все столбцы его AABB (с
    余白) должны пройти 持つか(cx, cz). Первый непрошедший кусок обрывает луч (как стена). Результат проверок
    столбцов кэшируется (соседние куски делят столбцы)."""
    済 = {}
    使える = 0.0
    for a, b in 区切る(長さ, 片長):
        for col in 箱の列(区間の箱(始, 向き, a, b, 余白)):
            ok = 済.get(col)
            if ok is None:
                ok = bool(持つか(col[0], col[1]))
                済[col] = ok
            if not ok:
                return 使える
        使える = b
    return 使える


def 線分と箱(始, 向き, 長さ, 箱):
    """Метод плит: расстояние t ∈ [0, 長さ], на котором луч входит в AABB, или None. Начало внутри — 0."""
    t0 = 0.0
    t1 = float(長さ)
    for i in range(3):
        o = 始[i]
        d = 向き[i]
        lo = 箱[i]
        hi = 箱[i + 3]
        if abs(d) < 1e-12:
            if o < lo or o > hi:
                return None
            continue
        inv = 1.0 / d
        ta = (lo - o) * inv
        tb = (hi - o) * inv
        if ta > tb:
            ta, tb = tb, ta
        if ta > t0:
            t0 = ta
        if tb < t1:
            t1 = tb
        if t0 > t1:
            return None
    return t0


def 広げる(箱, r):
    return (箱[0] - r, 箱[1] - r, 箱[2] - r, 箱[3] + r, 箱[4] + r, 箱[5] + r)


def 当たり(始, 向き, 長さ, 候補, 自分, 半径):
    """Цели луча: 候補 — [(id, AABB)], 自分 — id заклинателя (никогда не попадает). Бокс каждой цели расширен на
    半径. Возвращает [(t, id)] по возрастанию расстояния, каждый id — один раз."""
    out = {}
    for id, 箱 in 候補:
        if id == 自分 or id in out:
            continue
        t = 線分と箱(始, 向き, 長さ, 広げる(箱, 半径))
        if t is not None:
            out[id] = t
    return sorted(((t, id) for id, t in out.items()), key=lambda x: x[0])


def 道の点(始, 向き, から, まで, 毎):
    """Точки вдоль луча от から до まで через каждые 毎 блоков (для частиц следа)."""
    if 毎 <= 0 or まで <= から:
        return []
    out = []
    t = float(から)
    while t <= まで + 1e-9:
        out.append(点(始, 向き, t))
        t += 毎
    return out


# ------------------------------------------------------------------------------------------- время

def 冷却残り(今ms, 終ms):
    """Сколько секунд ещё перезарядка (0 — готов)."""
    return max(0.0, (float(終ms) - float(今ms)) / 1000.0)


def 秒の文字(秒):
    """Секунды для сообщения: «2.4», без хвоста «.0» («3»)."""
    s = "%.1f" % (math.ceil(float(秒) * 10.0 - 1e-9) / 10.0)
    return s[:-2] if s.endswith(".0") else s


def 充填棒(charge, 長さ):
    """Полоска заряда в MiniMessage: заполненная часть голубая, остальное — тёмно-серая."""
    n = max(1, int(長さ))
    k = int(math.floor(挟む(float(charge), 0.0, 1.0) * n + 1e-9))
    s = ""
    if k > 0:
        s += "<#7fd8ff>" + "|" * k + "</#7fd8ff>"
    if k < n:
        s += "<dark_gray>" + "|" * (n - k) + "</dark_gray>"
    return s
