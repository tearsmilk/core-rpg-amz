package core.amazake.systems.coreportals.anim;

/** Стадия жизни изумрудного портала. */
public enum RingPhase {
    /** В центре загорается и пульсирует зелёная точка. */
    SPARK,
    /** Чёрная дыра формируется: пустота растёт из центра, кольцо раскручивается и расширяется. */
    FORM,
    /** Открыт: в него можно войти. */
    IDLE,
    /** Кольцо раскручивается быстрее и схлопывается в точку, вспышка. */
    COLLAPSE,
    /** Всё убрано. */
    DONE
}
