package core.amazake.systems.coreportals.anim;

/** Стадия жизни портала. */
public enum Phase {
    /** Земля трескается, летят угли. */
    CRACK,
    /** Рама поднимается из-под земли. */
    RISE,
    /** Поверхность раскрывается от средней линии. */
    OPEN,
    /** Открыт: в него можно войти. */
    IDLE,
    /** Поверхность схлопывается к средней линии. */
    CLOSE_SURFACE,
    /** Рама уходит под землю. */
    CLOSE_FRAME,
    /** Всё убрано. */
    DONE
}
