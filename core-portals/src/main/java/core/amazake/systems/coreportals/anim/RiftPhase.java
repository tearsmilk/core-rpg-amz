package core.amazake.systems.coreportals.anim;

/** Стадия жизни лазуритового разлома. */
public enum RiftPhase {
    /** В воздухе появляется зубчатая светящаяся трещина и растёт вверх и вниз. */
    CRACK,
    /** Трещина раздваивается: края расходятся, вокруг бегут тонкие трещинки пространства. */
    SPLIT,
    /** Края рвутся в стороны и раскрываются в большой круглый разлом, внутри закручивается вихрь. */
    TEAR,
    /** Открыт: в него можно войти. */
    IDLE,
    /** Разлом стягивается обратно в трещину, трещина гаснет. */
    SEAL,
    /** Всё убрано. */
    DONE
}
